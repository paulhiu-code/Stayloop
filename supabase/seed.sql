-- Availability for the next 90 days (~90% open, deterministic blocked nights)
INSERT INTO availability_calendar (property_id, date, is_available, source)
SELECT
  p.id,
  gs.day::date,
  (abs(hashtext(p.id::text || gs.day::text)) % 10) <> 0,
  'manual'
FROM properties p
CROSS JOIN generate_series(CURRENT_DATE, CURRENT_DATE + interval '89 days', interval '1 day') AS gs(day)
WHERE p.host_id = '11111111-1111-1111-1111-111111111111'
ON CONFLICT (property_id, date) DO NOTHING;
